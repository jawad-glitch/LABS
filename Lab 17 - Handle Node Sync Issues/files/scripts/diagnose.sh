#!/bin/bash
source "$(dirname "$0")/node_ops.sh"
H=$LAB_ROOT
OUT="$H/logs/diagnostic-report.json"
TS=$(date -u +%Y-%m-%dT%H:%M:%SZ)
declare -A DATA

probe_node() {
  local n=$1
  local bn pc sy pel eline
  bn=$(rpc_call $n eth_blockNumber '[]' 2>/dev/null | python3 -c 'import sys,json;print(json.load(sys.stdin).get("result","0x0"))' 2>/dev/null || echo "0x0")
  pc=$(rpc_call $n net_peerCount '[]' 2>/dev/null | python3 -c 'import sys,json;print(json.load(sys.stdin).get("result","0x0"))' 2>/dev/null || echo "0x0")
  sy=$(rpc_call $n eth_syncing '[]' 2>/dev/null | python3 -c 'import sys,json;r=json.load(sys.stdin).get("result");print("false" if r is False else json.dumps(r))' 2>/dev/null || echo "null")
  local pid=$(cat "$H/logs/${n}.pid" 2>/dev/null)
  if [ -n "$pid" ] && kill -0 $pid 2>/dev/null; then pel=true; else pel=false; fi
  eline=$(grep -iE 'error|corrupt|exception|fail' "$H/logs/${n}.log" 2>/dev/null | tail -1 | cut -c1-180)
  local bn_dec=$((16#${bn#0x}))
  local pc_dec=$((16#${pc#0x}))
  DATA[${n}_running]=$pel
  DATA[${n}_reach]=$([ "$bn" != "0x0" ] || grep -q result <(rpc_call $n web3_clientVersion 2>/dev/null) && echo true || echo false)
  DATA[${n}_block_hex]=$bn
  DATA[${n}_block_dec]=$bn_dec
  DATA[${n}_peer_dec]=$pc_dec
  DATA[${n}_sync]=$sy
  DATA[${n}_err]=${eline:-null}
}

probe_node node1
probe_node node2
consistent=false
[ "${DATA[node1_block_dec]}" = "${DATA[node2_block_dec]}" ] && consistent=true
faults=()
[ "${DATA[node1_peer_dec]}" = "0" ] && faults+=("node1 peer count is 0")
[ "${DATA[node2_peer_dec]}" = "0" ] && faults+=("node2 peer count is 0")
[ "${DATA[node1_block_dec]}" != "${DATA[node2_block_dec]}" ] && faults+=("node block heights diverge (node1=${DATA[node1_block_dec]} node2=${DATA[node2_block_dec]})")
grep -qi 'rocksdb\|corruption' "$H/logs/node2.log" 2>/dev/null && faults+=("RocksDB Corruption in node2 log")
grep -qi 'rocksdb\|corruption' "$H/logs/node1.log" 2>/dev/null && faults+=("RocksDB Corruption in node1 log")
[ "${DATA[node2_sync]}" != "false" ] && [ "${DATA[node2_sync]}" != "null" ] && faults+=("node2 syncing object non-false")
[ "${DATA[node1_sync]}" != "false" ] && [ "${DATA[node1_sync]}" != "null" ] && faults+=("node1 syncing object non-false")

python3 - "$OUT" "$TS" "$consistent" "${#faults[@]}" "${faults[@]}" "${DATA[@]@Q}" <<'PY'
import sys, json, os
out, ts, consistent, nfaults, *rest = sys.argv[1:]
faults = rest[:int(nfaults)]
data_raw = rest[int(nfaults):]
# data_raw contains bash-quoted tokens from "${DATA[@]@Q}" ; re-parse crudely
data = {}
for tok in data_raw:
    try:
        s = eval(tok)  # safe: generated by bash @Q
        if "=" in s: pass
    except: pass
# Simpler: rely on env already popped by diagnose; here we hardcode fallback if parse fails
# For robustness, regenerate from files directly
PY
# Fallback: emit JSON via jq to be safe and deterministic
cat > "$OUT" <<JSON
{
  "report_timestamp": "$TS",
  "nodes": {
    "node1": {
      "process_running": ${DATA[node1_running]},
      "rpc_reachable": ${DATA[node1_reach]},
      "block_number_hex": "${DATA[node1_block_hex]}",
      "block_number_dec": ${DATA[node1_block_dec]},
      "peer_count_dec": ${DATA[node1_peer_dec]},
      "sync_status": "${DATA[node1_sync]}",
      "latest_error_log_line": $( [ "${DATA[node1_err]}" = "null" ] && echo null || python3 -c 'import json,sys;print(json.dumps(sys.argv[1]))' "${DATA[node1_err]}" )
    },
    "node2": {
      "process_running": ${DATA[node2_running]},
      "rpc_reachable": ${DATA[node2_reach]},
      "block_number_hex": "${DATA[node2_block_hex]}",
      "block_number_dec": ${DATA[node2_block_dec]},
      "peer_count_dec": ${DATA[node2_peer_dec]},
      "sync_status": "${DATA[node2_sync]}",
      "latest_error_log_line": $( [ "${DATA[node2_err]}" = "null" ] && echo null || python3 -c 'import json,sys;print(json.dumps(sys.argv[1]))' "${DATA[node2_err]}" )
    }
  },
  "chain_consistent": $consistent,
  "detected_faults": $(printf '%s\n' "${faults[@]}" | python3 -c 'import sys,json;print(json.dumps([l.strip() for l in sys.stdin if l.strip()]))')
}
JSON
python3 -c "import json;json.load(open('$OUT'));print('diagnose: valid JSON, faults:', len(json.load(open('$OUT'))['detected_faults']))"
exit 0
