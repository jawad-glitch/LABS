#!/bin/bash
echo "=== PoA Network Status Check ==="
echo ""
echo "1. Network ID:"
curl -s -X POST -H "Content-Type: application/json" -d '{"jsonrpc":"2.0","method":"net_version","params":[],"id":1}' http://localhost:8545 | python3 -c "import sys,json;print('Network ID:',json.load(sys.stdin).get('result','?'))"
echo ""
echo "2. Chain ID:"
curl -s -X POST -H "Content-Type: application/json" -d '{"jsonrpc":"2.0","method":"eth_chainId","params":[],"id":1}' http://localhost:8545 | python3 -c "import sys,json;r=json.load(sys.stdin).get('result','0x0');print('Chain ID:',int(r,16))"
echo ""
echo "3. Current Block:"
curl -s -X POST -H "Content-Type: application/json" -d '{"jsonrpc":"2.0","method":"eth_blockNumber","params":[],"id":1}' http://localhost:8545 | python3 -c "import sys,json;r=json.load(sys.stdin).get('result','0x0');print('Block Number:',int(r,16))"
echo ""
echo "4. Connected Peers:"
curl -s -X POST -H "Content-Type: application/json" -d '{"jsonrpc":"2.0","method":"net_peerCount","params":[],"id":1}' http://localhost:8545 | python3 -c "import sys,json;r=json.load(sys.stdin).get('result','0x0');print('Peer Count:',int(r,16))"
echo ""
echo "5. Current Gas Price:"
curl -s -X POST -H "Content-Type: application/json" -d '{"jsonrpc":"2.0","method":"eth_gasPrice","params":[],"id":1}' http://localhost:8545 | python3 -c "import sys,json;r=json.load(sys.stdin).get('result','0x0');print('Gas Price:',int(r,16),'wei')"
echo ""
echo "6. Mining Status:"
curl -s -X POST -H "Content-Type: application/json" -d '{"jsonrpc":"2.0","method":"eth_mining","params":[],"id":1}' http://localhost:8545 | python3 -c "import sys,json;print('Mining:',json.load(sys.stdin).get('result','?'))"
echo ""
echo "=== Status Check Complete ==="
